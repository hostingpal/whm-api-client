package cli

import (
	"bytes"
	"context"
	"os"
	"path/filepath"
	"strings"
	"testing"
)

const domainInfoOverlay = `{
  "schema_version": "1.0",
  "family": "uapi",
  "group": "DomainInfo",
  "operations": {
    "uapi:DomainInfo/list_domains": {},
    "uapi:DomainInfo/primary_domain": {"unwrap": "primary_domain"}
  }
}`

func writeOverlayDir(t *testing.T, files map[string]string) string {
	t.Helper()
	dir := t.TempDir()
	for _, family := range []string{"uapi", "whm"} {
		if err := os.MkdirAll(filepath.Join(dir, family), 0o755); err != nil {
			t.Fatal(err)
		}
	}
	if err := os.WriteFile(filepath.Join(dir, "config.json"), []byte(`{"schema_version":"1.0","scope":"listed"}`), 0o600); err != nil {
		t.Fatal(err)
	}
	for name, content := range files {
		if err := os.WriteFile(filepath.Join(dir, name), []byte(content), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	return dir
}

func runCLI(t *testing.T, args ...string) (int, string) {
	t.Helper()
	var stdout, stderr bytes.Buffer
	code := Run(context.Background(), args, &stdout, &stderr)
	return code, stdout.String() + stderr.String()
}

func TestOverlayValidateAndGeneratePHP(t *testing.T) {
	mapPath := pinnedParityMap(t)
	overlay := writeOverlayDir(t, map[string]string{"uapi/DomainInfo.json": domainInfoOverlay})
	root := t.TempDir()

	if code, out := runCLI(t, "overlay", "validate", "--map", mapPath, "--overlay", overlay); code != 0 || !strings.Contains(out, "1 groups, 2 operations") {
		t.Fatalf("validate %d: %s", code, out)
	}
	if code, out := runCLI(t, "generate", "php", "--map", mapPath, "--overlay", overlay, "--root", root, "--check"); code != 1 {
		t.Fatalf("check before write %d: %s", code, out)
	}
	if code, out := runCLI(t, "generate", "php", "--map", mapPath, "--overlay", overlay, "--root", root); code != 0 {
		t.Fatalf("write %d: %s", code, out)
	}
	if code, out := runCLI(t, "generate", "php", "--map", mapPath, "--overlay", overlay, "--root", root, "--check"); code != 0 {
		t.Fatalf("check after write %d: %s", code, out)
	}
	group := filepath.Join(root, "src/Api/Uapi/DomainInfo.php")
	content, err := os.ReadFile(group)
	if err != nil || !strings.Contains(string(content), "public function listDomains(") {
		t.Fatalf("generated group %v: %s", err, content)
	}
	if err := os.WriteFile(group, append(content, '\n'), 0o600); err != nil {
		t.Fatal(err)
	}
	if code, out := runCLI(t, "generate", "php", "--map", mapPath, "--overlay", overlay, "--root", root, "--check"); code != 1 || !strings.Contains(out, "src/Api/Uapi/DomainInfo.php") {
		t.Fatalf("check after edit %d: %s", code, out)
	}
}

func TestGeneratePHPRemovesOnlyStaleGeneratedFiles(t *testing.T) {
	mapPath := pinnedParityMap(t)
	overlay := writeOverlayDir(t, map[string]string{"uapi/DomainInfo.json": domainInfoOverlay})
	root := t.TempDir()
	stale := filepath.Join(root, "src/Api/Uapi/Old.php")
	handWritten := filepath.Join(root, "src/Api/Uapi/HandWritten.php")
	if err := os.MkdirAll(filepath.Dir(stale), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(stale, []byte("<?php\n/** Generated by tools/api-map from the pinned API map and docs/api/overlay; do not edit. */\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(handWritten, []byte("<?php\n// hand-written\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if code, out := runCLI(t, "generate", "php", "--map", mapPath, "--overlay", overlay, "--root", root); code != 0 {
		t.Fatalf("write %d: %s", code, out)
	}
	if _, err := os.Stat(stale); !os.IsNotExist(err) {
		t.Fatal("stale generated file kept")
	}
	if _, err := os.Stat(handWritten); err != nil {
		t.Fatal("hand-written file removed")
	}
}

func TestOverlayProblemsFailValidation(t *testing.T) {
	mapPath := pinnedParityMap(t)
	broken := strings.Replace(domainInfoOverlay, `"unwrap": "primary_domain"`, `"unwrap": "missing_field"`, 1)
	overlay := writeOverlayDir(t, map[string]string{"uapi/DomainInfo.json": broken})
	if code, out := runCLI(t, "overlay", "validate", "--map", mapPath, "--overlay", overlay); code != 1 || !strings.Contains(out, "unwrap field missing_field") {
		t.Fatalf("expected failure, got %d: %s", code, out)
	}
}
